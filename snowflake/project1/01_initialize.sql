-- Project 1 setup. Run once after the seven tables in ZOMATO.SOURCES are ready.
-- IF NOT EXISTS preserves the first source snapshot on subsequent executions.
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS ZOMATO_LAYER_REFACTOR;
CREATE SCHEMA IF NOT EXISTS ZOMATO_LAYER_REFACTOR.SOURCES;
CREATE SCHEMA IF NOT EXISTS ZOMATO_LAYER_REFACTOR.STAGING;
CREATE SCHEMA IF NOT EXISTS ZOMATO_LAYER_REFACTOR.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS ZOMATO_LAYER_REFACTOR.CORE;
CREATE SCHEMA IF NOT EXISTS ZOMATO_LAYER_REFACTOR.MARTS;
CREATE SCHEMA IF NOT EXISTS ZOMATO_LAYER_REFACTOR.SNAPSHOTS;

-- Clone only the raw tables. Do not clone Project 0's derived or AI schemas.
CREATE TABLE IF NOT EXISTS ZOMATO_LAYER_REFACTOR.SOURCES.RESTAURANTS CLONE ZOMATO.SOURCES.RESTAURANTS;
CREATE TABLE IF NOT EXISTS ZOMATO_LAYER_REFACTOR.SOURCES.FOOD CLONE ZOMATO.SOURCES.FOOD;
CREATE TABLE IF NOT EXISTS ZOMATO_LAYER_REFACTOR.SOURCES.MENU CLONE ZOMATO.SOURCES.MENU;
CREATE TABLE IF NOT EXISTS ZOMATO_LAYER_REFACTOR.SOURCES.ORDER_ITEMS CLONE ZOMATO.SOURCES.ORDER_ITEMS;
CREATE TABLE IF NOT EXISTS ZOMATO_LAYER_REFACTOR.SOURCES.ORDERS CLONE ZOMATO.SOURCES.ORDERS;
CREATE TABLE IF NOT EXISTS ZOMATO_LAYER_REFACTOR.SOURCES.REVIEWS CLONE ZOMATO.SOURCES.REVIEWS;
CREATE TABLE IF NOT EXISTS ZOMATO_LAYER_REFACTOR.SOURCES.USERS CLONE ZOMATO.SOURCES.USERS;

CREATE ROLE IF NOT EXISTS DBT_LAYER_REFACTOR_ROLE;
GRANT USAGE ON WAREHOUSE ZOMATO_WH TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT USAGE ON DATABASE ZOMATO_LAYER_REFACTOR TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ZOMATO_LAYER_REFACTOR TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ZOMATO_LAYER_REFACTOR.SOURCES TO ROLE DBT_LAYER_REFACTOR_ROLE;

GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_LAYER_REFACTOR.STAGING TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_LAYER_REFACTOR.INTERMEDIATE TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_LAYER_REFACTOR.CORE TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_LAYER_REFACTOR.MARTS TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_LAYER_REFACTOR.SNAPSHOTS TO ROLE DBT_LAYER_REFACTOR_ROLE;

SET project1_user = CURRENT_USER();
GRANT ROLE DBT_LAYER_REFACTOR_ROLE TO USER IDENTIFIER($project1_user);
