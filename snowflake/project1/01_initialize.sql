-- Project 1 setup. Run once after the seven tables in ZOMATO.SOURCES are ready.
-- IF NOT EXISTS preserves the first source snapshot on subsequent executions.
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS ZOMATO_DLR;
CREATE SCHEMA IF NOT EXISTS ZOMATO_DLR.SOURCES;
CREATE SCHEMA IF NOT EXISTS ZOMATO_DLR.STAGING;
CREATE SCHEMA IF NOT EXISTS ZOMATO_DLR.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS ZOMATO_DLR.CORE;
CREATE SCHEMA IF NOT EXISTS ZOMATO_DLR.MARTS;
CREATE SCHEMA IF NOT EXISTS ZOMATO_DLR.SNAPSHOTS;

-- Snapshot only the raw tables. Do not copy Project 0's derived or AI schemas.
CREATE TABLE IF NOT EXISTS ZOMATO_DLR.SOURCES.RESTAURANTS CLONE ZOMATO.SOURCES.RESTAURANTS;
CREATE TABLE IF NOT EXISTS ZOMATO_DLR.SOURCES.FOOD CLONE ZOMATO.SOURCES.FOOD;
CREATE TABLE IF NOT EXISTS ZOMATO_DLR.SOURCES.MENU CLONE ZOMATO.SOURCES.MENU;
CREATE TABLE IF NOT EXISTS ZOMATO_DLR.SOURCES.ORDER_ITEMS CLONE ZOMATO.SOURCES.ORDER_ITEMS;
CREATE TABLE IF NOT EXISTS ZOMATO_DLR.SOURCES.ORDERS CLONE ZOMATO.SOURCES.ORDERS;
CREATE TABLE IF NOT EXISTS ZOMATO_DLR.SOURCES.REVIEWS CLONE ZOMATO.SOURCES.REVIEWS;
-- Passwords are not used by dbt models or the experiment.
CREATE TABLE IF NOT EXISTS ZOMATO_DLR.SOURCES.USERS AS
SELECT * EXCLUDE PASSWORD FROM ZOMATO.SOURCES.USERS;

CREATE ROLE IF NOT EXISTS DBT_LAYER_REFACTOR_ROLE;
GRANT USAGE ON WAREHOUSE ZOMATO_WH TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT USAGE ON DATABASE ZOMATO_DLR TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ZOMATO_DLR TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ZOMATO_DLR.SOURCES TO ROLE DBT_LAYER_REFACTOR_ROLE;

GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_DLR.STAGING TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_DLR.INTERMEDIATE TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_DLR.CORE TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_DLR.MARTS TO ROLE DBT_LAYER_REFACTOR_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ZOMATO_DLR.SNAPSHOTS TO ROLE DBT_LAYER_REFACTOR_ROLE;

SET project1_user = CURRENT_USER();
GRANT ROLE DBT_LAYER_REFACTOR_ROLE TO USER IDENTIFIER($project1_user);
