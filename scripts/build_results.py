"""Build experiments/RESULTS.md, the single reference write-up of the experiment, from raw attempts.

Every number is computed from experiments/run.local attempts and grade files; nothing is typed
in by hand. Run from the repository root:

    python3 scripts/build_results.py            # rewrite experiments/RESULTS.md
    python3 scripts/build_results.py --check    # fail if experiments/RESULTS.md is out of date
"""

import argparse
import json
import random
import re
import statistics as st
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / "experiments" / "run.local"
OUT = ROOT / "experiments" / "RESULTS.md"
ARMS = "ABCDEF"
POLICY = {"Q22", "Q23", "Q24"}
QIDS = [f"Q{i:02d}" for i in range(1, 26)]
DATA_Q = [q for q in QIDS if q not in POLICY]
MODELS = {
    "gpt-4.1": dict(dir="af_25_v2_rep{}", grades="af_25_v2_grades.json", prefix="", price=(2.0, 8.0)),
    "gpt-6-luna": dict(dir="af_25_luna_rep{}", grades="af_25_luna_grades.json", prefix="luna_", price=(0.10, 0.50)),
}
ARM_NAME = {"A": "source + staging", "B": "+ intermediate", "C": "+ core", "D": "+ marts",
            "E": "+ MetricFlow metrics", "F": "+ business glossary"}


def load():
    data = {}
    for m, cfg in MODELS.items():
        grades = json.loads((RUN / cfg["grades"]).read_text())
        rows = []
        for rep in (1, 2, 3):
            for f in sorted((RUN / cfg["dir"].format(rep) / "attempts").glob("*.json")):
                d = json.loads(f.read_text())
                key = f"{d['arm']}-{d['question_id']}"
                steps = d["steps"]
                stats = [s.get("model_stats") or {} for s in steps]
                errs = [s["tool_error"] for s in steps if s.get("tool_error")]
                rows.append(dict(
                    arm=d["arm"], q=d["question_id"], rep=rep, score=grades[key][f"{cfg['prefix']}rep{rep}"],
                    outcome=d["outcome"], status=d["status"], sec=d["total_seconds"], nsteps=len(steps),
                    pt=sum(s.get("prompt_tokens") or 0 for s in stats),
                    ct=sum(s.get("completion_tokens") or 0 for s in stats), errs=errs,
                    temperature=d.get("temperature"), seed=d.get("seed"), ctx=d.get("context_sha256"),
                    started=d["started_utc"]))
        assert len(rows) == 450, (m, len(rows))
        data[m] = rows
    return data


def sd(xs):
    return st.stdev(xs) if len(xs) > 1 else 0.0


def f2(x):
    return f"{x:.2f}"


def pct(x):
    return f"{100 * x:.1f}%"


def rep_totals(rows, arm, qs):
    return [sum(r["score"] for r in rows if r["arm"] == arm and r["rep"] == k and r["q"] in qs) for k in (1, 2, 3)]


def qmean(rows, arm, q):
    return st.mean(r["score"] for r in rows if r["arm"] == arm and r["q"] == q)


def boot_ci(a, b, qs, n=10000, seed=20261027):
    """Paired bootstrap over questions of mean(b) - mean(a); a, b are dicts question -> mean score."""
    diffs = [b[q] - a[q] for q in qs]
    rnd = random.Random(seed)
    means = sorted(st.mean(rnd.choices(diffs, k=len(diffs))) for _ in range(n))
    return st.mean(diffs), means[int(0.025 * n)], means[int(0.975 * n)]


def quant(xs, p):
    xs = sorted(xs)
    i = (len(xs) - 1) * p
    lo, hi = int(i), min(int(i) + 1, len(xs) - 1)
    return xs[lo] + (xs[hi] - xs[lo]) * (i - lo)


def table(head, rows, align=None):
    align = align or ["---"] + ["---:"] * (len(head) - 1)
    out = ["| " + " | ".join(head) + " |", "| " + " | ".join(align) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def build(data):
    L = []
    w = L.append
    prices = {m: MODELS[m]["price"] for m in MODELS}

    # ---------- derived structures
    by = {m: data[m] for m in data}
    qm = {m: {a: {q: qmean(by[m], a, q) for q in QIDS} for a in ARMS} for m in by}

    w("# Experiment results: reference record\n")
    w("> Generated by `scripts/build_results.py` from the raw attempts and grade files in "
      "`experiments/run.local/`. Do not edit by hand; rerun the script. "
      "`python3 scripts/build_results.py --check` fails if this file is stale.\n")
    w("This document is the single reference for what the experiment measured. Where another "
      "document (older reports, the Medium article) disagrees with it, this one wins, subject to "
      "the stated limits. Sections 1-2 say what was run and how it was scored; 3-9 are results; "
      "10 is a claim register that says which conclusions the data does and does not support.\n")

    # ---------- 1 design
    w("## 1. What was run\n")
    runs = {m: sorted({r["started"][:10] for r in by[m]}) for m in by}
    temps = {m: sorted({str(r["temperature"]) for r in by[m]}) for m in by}
    seeds = {m: sorted({str(r["seed"]) for r in by[m]}) for m in by}
    w(table(["Item", "gpt-4.1", "gpt-6-luna"], [
        ["Attempts", len(by["gpt-4.1"]), len(by["gpt-6-luna"])],
        ["Design", "25 questions x 6 arms x 3 repetitions"] * 1 + ["same"],
        ["Run dates (UTC)", ", ".join(runs["gpt-4.1"]), ", ".join(runs["gpt-6-luna"])],
        ["Temperature recorded", ", ".join(temps["gpt-4.1"]), ", ".join(temps["gpt-6-luna"])],
        ["Seed recorded", ", ".join(seeds["gpt-4.1"]), ", ".join(seeds["gpt-6-luna"])],
        ["Other setting", "-", "reasoning_effort=high (from the run reports, not stored per attempt)"],
    ], ["---", "---", "---"]))
    w("")
    w("**Arms.** Each arm inherits the SQL access of the previous one:\n")
    w(table(["Arm", "Agent can use"], [[a, ARM_NAME[a]] for a in ARMS], ["---", "---"]))
    w("")
    w("A and B use SQL only; D adds four aggregate marts; E adds 19 MetricFlow metrics; "
      "F adds the versioned business glossary (`context/v1`). Same Snowflake snapshot "
      "(`ZOMATO_DLR`), same question text and same query limits for every attempt. Reference "
      "answers were never shown to the evaluated model.\n")
    w("**Questions.** 25 total. 22 are *data questions* (Q01-Q21, Q25) any arm could in principle "
      "answer. 3 are *policy questions* (Q22-Q24) that need business rules supplied only in arm F "
      "(`rating_count >= 100`, restaurant-city geography, repeat-customer definition).\n")
    w("**Outcomes.** All 900 attempts have status `completed`. An attempt either gives a final answer "
      "or asks a clarification question (scored 0).\n")

    # ---------- 2 scoring
    w("## 2. How answers were scored\n")
    w("- Score per attempt is 0 or 1 from `scripts/autograde.py`, which compares the final answer to "
      "`experiments/gold_25_results.json` (gold SQL re-run on 2026-10-25). It ignores arm and model.")
    w("- Tolerances: +/-INR 0.01 for money totals; +/-0.01 percentage points for rates, shares and "
      "percent changes; +/-0.01 for averages and correlations; +/-INR 0.05 per Q20 decomposition "
      "component; integer counts and identities exact.")
    w("- A clarification or failed query scores 0. Q22-Q24 score 0 in arms A-E **by rule**, because the "
      "eligibility rules exist only in F.")
    w("- A first manual pass disagreed with the script on 13 of 900 attempts (all gpt-4.1); the script's "
      "score was adopted for all 13 (list in `experiments/README.md`). Eleven manual scores were too "
      "lenient, two too strict. Luna's manual and scripted scores were identical.")
    w("- The script checks that required values and statements are present and correct. It cannot detect "
      "a correct number used for the wrong population.")
    w("- **Independence:** the same person wrote the questions, the reference answers, the grader "
      "requirements and the glossary rules. The gold SQL is not published (gitignored); "
      "`gold_25_results.json` holds its output.")
    w("- Q07, Q14 and Q20 depend on tight percentage arithmetic. gpt-4.1 often misses by 0.02-0.04 pp "
      "(for example 33.732% vs 33.7684%) and fails. This is a rubric-sensitivity point: a looser "
      "tolerance would change gpt-4.1's scores.\n")
    w("**Statistics used.** Mean and *sample* standard deviation (n-1) of the **three per-repetition "
      "totals** of each arm (n = 3). Differences marked with a bootstrap interval resample the 22 data "
      "questions (paired, 10,000 draws, seed 20261027) using each question's mean over the three "
      "repetitions; this reflects question-sampling uncertainty, not model stochasticity alone.\n")

    # ---------- 3 headline
    w("## 3. Headline results\n")
    tot = {m: sum(r["score"] for r in by[m]) for m in by}
    w(table(["Model", "Correct / 450", "Rate", "Mean per run of 150", "Per-rep totals"], [
        [m, tot[m], pct(tot[m] / 450), f2(tot[m] / 3),
         " / ".join(str(sum(r["score"] for r in by[m] if r["rep"] == k)) for k in (1, 2, 3))]
        for m in by]))
    w("")
    w(f"Overall: gpt-4.1 **{pct(tot['gpt-4.1']/450)}**, gpt-6-luna **{pct(tot['gpt-6-luna']/450)}**.\n")

    # ---------- 4 per arm
    w("## 4. Correctness by arm\n")
    for m in by:
        w(f"### {m}\n")
        rows = []
        for a in ARMS:
            t = rep_totals(by[m], a, set(QIDS))
            d = rep_totals(by[m], a, set(DATA_Q))
            p = rep_totals(by[m], a, POLICY)
            rows.append([a, ARM_NAME[a], f"{f2(st.mean(d))} +/- {f2(sd(d))}",
                         f"{f2(st.mean(p))}", f"{f2(st.mean(t))} +/- {f2(sd(t))}",
                         pct(st.mean(t) / 25), " / ".join(map(str, t))])
        w(table(["Arm", "Access", "Data /22", "Policy /3", "Total /25", "Total %", "Reps"], rows,
                ["---", "---", "---:", "---:", "---:", "---:", "---:"]))
        w("")
    w("Policy questions are 0 in A-E for both models by rule; F scores 3/3 for both. The "
      "A-to-F total gain therefore mixes a definition effect (policy) with a data effect. "
      "Use the data columns for layer effects.\n")

    # ---------- 5 layer effects
    w("## 5. What each layer adds (data questions only)\n")
    w("Mean change in correct data answers per question-mean (x22 = answers per run), with a paired "
      "bootstrap 95% interval over questions. An interval that includes 0 means the data cannot "
      "distinguish the layers.\n")
    steps = [("A", "B"), ("B", "C"), ("C", "D"), ("C", "E"), ("D", "E"), ("E", "F"), ("C", "F"), ("A", "C"), ("A", "F")]
    for m in by:
        rows = []
        for a, b in steps:
            mean, lo, hi = boot_ci(qm[m][a], qm[m][b], DATA_Q)
            rows.append([f"{a} -> {b}", f"{round(mean*22, 2) + 0.0:+.2f}", f"[{lo*22:+.2f}, {hi*22:+.2f}]",
                         "excludes 0" if lo > 0 or hi < 0 else "includes 0"])
        w(f"**{m}** (answers per 22-question run)\n")
        w(table(["Step", "Change", "95% interval", "vs zero"], rows, ["---", "---:", "---:", "---"]))
        w("")
    w("**Model effect at equal access** (Luna minus gpt-4.1, data questions):\n")
    rows = []
    for a in ARMS:
        mean, lo, hi = boot_ci(qm["gpt-4.1"][a], qm["gpt-6-luna"][a], DATA_Q)
        rows.append([a, f"{round(mean*22, 2) + 0.0:+.2f}", f"[{lo*22:+.2f}, {hi*22:+.2f}]"])
    w(table(["Arm", "Luna - gpt-4.1", "95% interval"], rows))
    lu_a = st.mean(rep_totals(by["gpt-6-luna"], "A", set(DATA_Q)))
    g_f = st.mean(rep_totals(by["gpt-4.1"], "F", set(DATA_Q)))
    g_best = max(st.mean(rep_totals(by["gpt-4.1"], a, set(DATA_Q))) for a in ARMS)
    w(f"\nOn data questions, Luna with source/staging only (arm A) scores {f2(lu_a)}/22; gpt-4.1's best "
      f"arm scores {f2(g_best)}/22 (arm F: {f2(g_f)}). Model choice moved the score more than any layer.\n")

    # ---------- 6 per question
    w("## 6. Per-question results\n")
    w("Cell = number of correct repetitions out of 3.\n")
    for m in by:
        w(f"### {m}\n")
        rows = [[q] + [str(round(qm[m][a][q] * 3)) for a in ARMS] for q in QIDS]
        w(table(["Q"] + list(ARMS), rows, ["---"] + ["---:"] * 6))
        w("")
    w("**Questions never answered correctly (0/3 in every arm where answerable):**\n")
    for m in by:
        never = [q for q in DATA_Q if all(qm[m][a][q] == 0 for a in ARMS)]
        w(f"- {m}: {', '.join(never) if never else 'none'}")
    w("")
    w("**Unstable cells (neither 0 nor 3 correct):**\n")
    for m in by:
        unstable = sum(1 for a in ARMS for q in QIDS if 0 < round(qm[m][a][q] * 3) < 3)
        w(f"- {m}: {unstable} of 150 arm-question cells")
    w("")

    # ---------- 7 behaviour
    w("## 7. Answers, clarifications and tool errors\n")
    rows = []
    for m in by:
        for a in ARMS:
            rs = [r for r in by[m] if r["arm"] == a]
            rows.append([m, a, sum(r["outcome"] == "clarification" for r in rs),
                         sum(bool(r["errs"]) for r in rs), sum(len(r["errs"]) for r in rs),
                         sum(any("timeout" in e.lower() or "connection" in e.lower() for e in r["errs"]) for r in rs)])
    w(table(["Model", "Arm", "Clarifications /75", "Attempts with tool error", "Tool errors", "Timeout / connection attempts"],
            rows, ["---", "---", "---:", "---:", "---:", "---:"]))
    w("")
    w("Clarifications and tool errors both score 0. A tool error does not always lose the attempt "
      "(the agent may retry).\n")

    # ---------- 8 cost
    w("## 8. Cost\n")
    w("Estimated LLM cost = prompt tokens x input price + completion tokens x output price, summed over "
      "all model steps of every attempt (including wrong ones). Excludes Snowflake compute, caching "
      "discounts, taxes and any pricing category not recorded.\n")
    w(f"**Prices used (USD per million tokens, input/output): gpt-4.1 {prices['gpt-4.1'][0]}/{prices['gpt-4.1'][1]}; "
      f"gpt-6-luna {prices['gpt-6-luna'][0]}/{prices['gpt-6-luna'][1]}. These are the author's figures. "
      "They are not recorded in the repository and could not be independently verified; confirm them "
      "against the provider price list for the run period.**\n")
    res_cost = {}
    for m in by:
        pi, po = prices[m]
        rows = []
        for a in ARMS:
            rs = [r for r in by[m] if r["arm"] == a]
            c = sum(r["pt"] * pi / 1e6 + r["ct"] * po / 1e6 for r in rs)
            k = sum(r["score"] for r in rs)
            res_cost[(m, a)] = (c, k, sum(r["pt"] for r in rs), sum(r["ct"] for r in rs))
            rows.append([a, f"${c:.4f}", k, f"${c/k:.5f}",
                         f"{st.mean(r['pt'] for r in rs):,.0f}", f"{st.mean(r['ct'] for r in rs):,.0f}",
                         f"{(sum(r['pt'] + r['ct'] for r in rs))/k:,.0f}"])
        c = sum(v[0] for (mm, _), v in res_cost.items() if mm == m)
        k = sum(v[1] for (mm, _), v in res_cost.items() if mm == m)
        rows.append(["All", f"${c:.4f}", k, f"${c/k:.5f}", "", "", ""])
        w(f"### {m}\n")
        w(table(["Arm", "Total cost", "Correct", "Cost per correct", "Mean prompt tok", "Mean completion tok",
                 "Tokens per correct"], rows))
        w("")
    cg = sum(v[0] for (mm, _), v in res_cost.items() if mm == "gpt-4.1") / tot["gpt-4.1"]
    cl = sum(v[0] for (mm, _), v in res_cost.items() if mm == "gpt-6-luna") / tot["gpt-6-luna"]
    tg = sum(v[2] + v[3] for (mm, _), v in res_cost.items() if mm == "gpt-4.1") / tot["gpt-4.1"]
    tl = sum(v[2] + v[3] for (mm, _), v in res_cost.items() if mm == "gpt-6-luna") / tot["gpt-6-luna"]
    w(f"**Cost ratio (gpt-4.1 / Luna) per correct answer: {cg/cl:.1f}x.** The price list alone is "
      f"{2.0/0.10:.0f}x on input and {8.0/0.50:.0f}x on output, so most of this ratio is price, not efficiency. "
      f"Price-independent view: tokens per correct answer are {tg:,.0f} (gpt-4.1) and {tl:,.0f} (Luna), "
      f"a ratio of {tg/tl:.2f}x.\n")
    for m in by:
        pa = res_cost[(m, "A")][0] / res_cost[(m, "A")][1]
        order = ", ".join(f"{a} {'<' if res_cost[(m, a)][0]/res_cost[(m, a)][1] < pa else '>='} A"
                          for a in "BCDEF")
        best = min(ARMS, key=lambda a: res_cost[(m, a)][0] / res_cost[(m, a)][1])
        fa = (res_cost[(m, 'F')][0] / res_cost[(m, 'F')][1]) / pa
        w(f"- {m}: cheapest per correct = arm {best}; cost per correct vs arm A ({order}); F/A = {fa:.2f}x.")
    w("")

    # ---------- 9 latency
    w("## 9. Latency and effort\n")
    w("End-to-end seconds per attempt (model calls plus database/MetricFlow execution). Steps = recorded "
      "model actions per attempt.\n")
    for m in by:
        rows = []
        for a in list(ARMS) + ["All"]:
            rs = [r for r in by[m] if a == "All" or r["arm"] == a]
            s = [r["sec"] for r in rs]
            rows.append([a, f2(st.median(s)), f2(st.mean(s)), f2(quant(s, 0.9)), f2(max(s)),
                         f2(st.mean(r["nsteps"] for r in rs))])
        w(f"### {m}\n")
        w(table(["Arm", "Median s", "Mean s", "p90 s", "Max s", "Mean steps"], rows))
        w("")
    w("Slowest attempts and whether a tool error was logged:\n")
    for m in by:
        slow = sorted(by[m], key=lambda r: -r["sec"])[:5]
        w(f"- {m}: " + "; ".join(f"{r['arm']}-{r['q']} r{r['rep']} {r['sec']:.0f}s "
                                  f"({'error logged' if r['errs'] else 'no error logged'})" for r in slow))
    for m in by:
        over = [r for r in by[m] if r["sec"] > 60]
        w(f"- {m}: {len(over)} attempts over 60 s, {sum(bool(r['errs']) for r in over)} with a logged tool error.")
    w("\nLatency does not rise monotonically with layers for either model; some slow attempts coincide "
      "with tool errors but not all slow outliers are explained by logged errors.\n")

    # ---------- 10 claims
    w("## 10. Claim register\n")
    g, l = by["gpt-4.1"], by["gpt-6-luna"]

    def dm(m, a):
        return st.mean(rep_totals(by[m], a, set(DATA_Q)))

    rows = [
        ["Intermediate (B) and core (C) layers improve gpt-4.1 data correctness",
         f"A {f2(dm('gpt-4.1','A'))} -> B {f2(dm('gpt-4.1','B'))} -> C {f2(dm('gpt-4.1','C'))} of 22",
         "A->C is supported (interval excludes 0); B->C alone is too, A->B alone is not distinguishable "
         "from 0 (section 5). Partly access, not modelling quality: Q18's age-segment label exists only in core."],
        ["Marts (D) add nothing over core (C)",
         f"gpt-4.1 C {f2(dm('gpt-4.1','C'))} vs D {f2(dm('gpt-4.1','D'))}; "
         f"Luna C {f2(dm('gpt-6-luna','C'))} vs D {f2(dm('gpt-6-luna','D'))}",
         "Supported as 'no detectable difference'. Not evidence marts are useless."],
        ["MetricFlow (E) adds nothing over core (C)",
         f"gpt-4.1 C {f2(dm('gpt-4.1','C'))} vs E {f2(dm('gpt-4.1','E'))}; "
         f"Luna C {f2(dm('gpt-6-luna','C'))} vs E {f2(dm('gpt-6-luna','E'))}",
         "Supported as 'no detectable difference' on these 25 questions."],
        ["Business glossary makes policy questions answerable", "A-E 0/3 and F 3/3 for both models",
         "True by construction: A-E score 0 by rule and the author wrote the rules. Shows the rules are "
         "needed, not that a glossary generally raises accuracy."],
        ["Glossary does not raise data-question accuracy",
         f"gpt-4.1 F {f2(dm('gpt-4.1','F'))} vs C-E; Luna F {f2(dm('gpt-6-luna','F'))}",
         "Consistent with the data; F's gpt-4.1 data score is lower than C-E."],
        ["Model choice outweighs layer choice",
         f"Luna arm A {f2(dm('gpt-6-luna','A'))} vs gpt-4.1 best {f2(g_best)} of 22",
         "Supported for these two models. Confounded: model, reasoning effort and temperature differ."],
        ["Luna is ~25x cheaper per correct answer", f"{cg/cl:.1f}x by estimated cost; {tg/tl:.2f}x by tokens",
         "Cost depends on unverified list prices; token-based gap is much smaller."],
        ["Luna is slower", "median/mean seconds in section 9", "Supported."],
        ["Results generalise to other data or workloads", "-", "Not supported: one dataset, 25 author-written "
         "questions, three repetitions, two models."],
    ]
    w(table(["Claim", "Evidence", "Verdict"], rows, ["---", "---", "---"]))
    w("")

    # ---------- 11 limits
    w("## 11. Limits\n")
    for t in [
        "One dataset snapshot, one domain (food delivery), 25 questions; the 900 attempts are 25 distinct "
        "questions each repeated, so effective sample size is nearer 25 than 900.",
        "Three repetitions give a coarse estimate of run-to-run spread (SD with n = 3).",
        "Author wrote questions, reference answers, grader rules and glossary; no independent grading.",
        "Models differ in more than capability (reasoning effort, temperature), so the model comparison is "
        "not a clean ablation.",
        "Strict percentage tolerances penalise hand arithmetic (Q07, Q14, Q20, Q12) and mostly affect "
        "gpt-4.1; a calculator tool or SQL-computed percentages was not tested.",
        "Cost figures use unverified prices and exclude warehouse compute.",
        "Layer effects are measured as additive access; the order of layers was not randomised, and a layer's "
        "value could differ if added to a different base.",
    ]:
        w(f"- {t}")
    w("")
    w("## 12. Reproduce\n")
    w("```\npython3 scripts/autograde.py              # confirm stored grades match the grader\n"
      "python3 scripts/summarize_experiments.py --input-price 2 --output-price 8      # gpt-4.1 overall\n"
      "python3 scripts/build_results.py           # regenerate this file\n```\n")
    return "\n".join(L).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build(load())
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit("experiments/RESULTS.md is out of date; run scripts/build_results.py")
        print("experiments/RESULTS.md is up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
